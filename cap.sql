-- Write a query to classify customers into spending brackets (e.g., low,medium, high).

SELECT
    c.customer_id,
    c.first_name,
    SUM(oi.total_price) AS total_spending,
    CASE
        WHEN SUM(oi.total_price) < 10000 THEN 'Low'
        WHEN SUM(oi.total_price) < 20000 THEN 'Medium'
        ELSE 'High'
    END AS spending_bracket
FROM customers c
LEFT JOIN orders o
    ON c.customer_id = o.customer_id
LEFT JOIN order_items oi
    ON o.order_id = oi.order_id
GROUP BY
    c.customer_id,
    c.first_name;
    
-- Analyze total revenue generated by each staff member based on their handled orders.


SELECT
    s.staff_id,
    s.first_name,
    s.last_name,
    COUNT(DISTINCT o.order_id) AS total_orders,
    COALESCE(SUM(oi.total_price), 0) AS total_revenue
FROM staffs s
LEFT JOIN orders o
    ON s.staff_id = o.staff_id
LEFT JOIN order_items oi
    ON o.order_id = oi.order_id
GROUP BY
    s.staff_id,
    s.first_name,
    s.last_name
ORDER BY total_revenue DESC;

-- Write a query to list products where stock quantity < 10 in any store.

SELECT
    p.product_id,
    p.product_name,
    s.store_id,
    s.store_name,
    st.quantity AS stock_quantity
FROM stocks st
INNER JOIN products p
    ON st.product_id = p.product_id
INNER JOIN stores s
    ON st.store_id = s.store_id
WHERE st.quantity < 10
ORDER BY st.quantity ASC;



