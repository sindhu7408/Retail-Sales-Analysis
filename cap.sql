-- Join orders, order_items, and products to display detailed line items.

select o.order_id,o.order_date,oi.item_id,p.product_id,p.product_name,oi.quantity,oi.list_price,oi.discount
from orders o
inner join order_items oi
on o.order_id = oi.order_id
inner join products p
on oi.product_id = p.product_id;

-- Write a query to group sales (total_price) by each store_id.

select s.store_id,s.store_name,sum(oi.total_price)
from stores s 
inner join orders o
on s.store_id = o.store_id
inner join order_items oi
on oi.order_id = o.order_id
group by s.store_id,s.store_name;

-- Use ORDER BY and LIMIT to get the top 5 most sold products by quantity.

select * from order_items;

select p.product_id,p.product_name,sum(oi.quantity) as total_quantity
from products p
inner join order_items oi 
on p.product_id = oi.product_id
group by p.product_id,p.product_name
order by total_quantity DESC limit 5;

